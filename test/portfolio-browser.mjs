// Run against a disposable/beta Showrunner instance. Creates a draft album; prints its ID for cleanup.
// ALBUM_TEST_URL, ALBUM_TEST_USER and ALBUM_TEST_PASSWORD must be set.
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';
const require = createRequire(import.meta.url);
const sharp = require('sharp');
const { chromium } = await import(pathToFileURL(process.env.PLAYWRIGHT_MODULE).href);
const base = process.env.ALBUM_TEST_URL;
assert(base && process.env.ALBUM_TEST_USER && process.env.ALBUM_TEST_PASSWORD);
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const imageRequests = []; page.on('request', request => { if (request.resourceType() === 'image') imageRequests.push(request.url()); });
const errors = []; page.on('pageerror', error => errors.push(error.message));
page.setDefaultTimeout(45000);
async function submitGalleryAction(name) {
  const [response] = await Promise.all([
    page.waitForResponse(response => response.request().method() === 'POST' && new URL(response.url()).pathname === '/admin/modules/portfolio'),
    page.getByRole('button', { name, exact: true }).click()
  ]);
  assert(response.ok(), name + ' must succeed');
  await response.finished();
}

