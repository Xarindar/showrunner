  assert.equal(await page.getByLabel('Gallery layout', { exact: true }).inputValue(), 'GRID');
  for (const name of ['Published']) assert.equal(await page.getByRole('switch', { name, exact: true }).isChecked(), false);
  await page.locator('summary').filter({ hasText: /^Archive gallery$/ }).click();
  await page.getByRole('switch', { name: 'Confirm archive', exact: true }).check();
