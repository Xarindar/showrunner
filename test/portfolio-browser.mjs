  await page.getByRole('button', { name: 'Gallery settings', exact: true }).click();
  assert.equal(await page.getByLabel('Gallery layout', { exact: true }).inputValue(), 'MASONRY');
  for (const name of ['Published']) {
    assert(await page.getByRole('switch', { name, exact: true }).isChecked());
    await page.getByRole('switch', { name, exact: true }).uncheck();
  }
  await page.getByLabel('Gallery layout', { exact: true }).selectOption('GRID');
  await submitGalleryAction('Save gallery settings');
