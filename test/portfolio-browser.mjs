  assert.equal(await page.getByRole('region', { name: 'Album photos', exact: true }).locator('button:has(img)').count(), 9);
  const initialImages = await page.getByRole('region', { name: 'Album photos', exact: true }).locator('img').evaluateAll(async images => {
    await Promise.all(images.map(image => image.decode()));
    return images.map(image => ({ src: image.currentSrc, width: image.naturalWidth }));
  });
  assert(initialImages.every(image => image.width <= 720), 'The grid must load thumbnail-sized files');
  const gridPaths = new Set(initialImages.map(image => new URL(image.src).pathname));
  assert(!imageRequests.some(src => { const url = new URL(src); return gridPaths.has(url.pathname) && url.searchParams.get('variant') === 'FULL'; }), 'Full images must not load before opening the viewer');
