  const compactWidth = (await firstThumbnail.boundingBox()).width;
  assert.equal(await density.getAttribute('aria-pressed'), 'false');
  await density.click();
  assert.equal(await density.getAttribute('aria-pressed'), 'true');
  assert((await firstThumbnail.boundingBox()).width > compactWidth, 'Large thumbnails must visibly increase the grid size');
  await density.click();
  assert.equal(await density.getAttribute('aria-pressed'), 'false');
  assert.equal((await firstThumbnail.boundingBox()).width, compactWidth);
  await page.screenshot({ path: '.impeccable/review/album-open-desktop.png', fullPage: true });
