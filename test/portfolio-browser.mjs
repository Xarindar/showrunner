  await page.getByRole('button', { name: 'Published (public) — switch to draft', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Published (public) — switch to draft', exact: true }).click();
  await page.getByRole('button', { name: 'Draft — publish gallery', exact: true }).waitFor();
