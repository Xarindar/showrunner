  await page.getByRole('region', { name: 'Album photos', exact: true }).locator('img').nth(8).waitFor();
  await page.getByRole('region', { name: 'Album photos', exact: true }).locator('img').evaluateAll(images => Promise.all(images.map(image => image.decode())));
  assert.equal(await page.getByRole('heading', { name: 'Start revision round', exact: true }).count(), 0);
  const photoRatios = await page.getByRole('region', { name: 'Album photos', exact: true }).locator('img').evaluateAll(images => images.map(image => ({actual: image.clientWidth / image.clientHeight, natural: image.naturalWidth / image.naturalHeight})));
