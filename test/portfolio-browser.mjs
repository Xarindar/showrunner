  const droppedFiles = await page.evaluateHandle(base64 => {
    const bytes = Uint8Array.from(atob(base64), character => character.charCodeAt(0));
    const transfer = new DataTransfer();
    transfer.items.add(new File([bytes], 'album-check-one.png', { type: 'image/png' }));
    transfer.items.add(new File([bytes], 'album-check-two.png', { type: 'image/png' }));
    transfer.items.add(new File(['not an image'], 'invalid-photo.txt', { type: 'text/plain' }));
    return transfer;
  }, image.toString('base64'));
  await page.getByRole('region', { name: 'Album photos', exact: true }).dispatchEvent('dragenter', { dataTransfer: droppedFiles });
  await page.getByText('Drop photos to upload', { exact: true }).waitFor();
  await page.getByRole('region', { name: 'Album photos', exact: true }).dispatchEvent('drop', { dataTransfer: droppedFiles });
  await droppedFiles.dispose();
  await page.getByRole('status').filter({ hasText: '2 photos added; 1 not uploaded.' }).waitFor({ timeout: 120000 });
  await page.getByRole('alert').filter({ hasText: 'Choose a JPG' }).waitFor();
  await page.getByRole('region', { name: 'Album photos', exact: true }).locator('img').nth(1).waitFor();
  await page.getByRole('region', { name: 'Album photos', exact: true }).locator('img').evaluateAll(images => Promise.all(images.map(image => image.decode())));
  assert.equal(await page.getByRole('region', { name: 'Album photos', exact: true }).locator('button:has(img)').count(), 2);
  await page.reload();
  await page.getByRole('img', { name: '2 photos', exact: true }).waitFor();
